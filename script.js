const languageButton = document.querySelector(".language-button");
const languageMenu = document.querySelector(".language-menu");
const currentLanguage = document.querySelector(".current-language");
const languageOptions = document.querySelectorAll("[data-language]");
const menuToggle = document.querySelector(".menu-toggle");
const mainNav = document.querySelector(".main-nav");

function setLanguage(language) {
  const copy = translations[language];
  if (!copy) return;

  document.documentElement.lang = language;
  currentLanguage.textContent = language.toUpperCase();
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const translation = copy[element.dataset.i18n];
    if (translation) element.textContent = translation;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const translation = copy[element.dataset.i18nAria];
    if (translation) element.setAttribute("aria-label", translation);
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const translation = copy[element.dataset.i18nAlt];
    if (translation) element.alt = translation;
  });
  languageOptions.forEach((option) => {
    if (option.dataset.language === language) option.setAttribute("aria-current", "true");
    else option.removeAttribute("aria-current");
  });

  const message = {
    it: "Ciao, vorrei avere informazioni sulle auto.",
    en: "Hello, I’d like some information about your cars.",
    de: "Hallo, ich hätte gerne Informationen zu Ihren Fahrzeugen."
  }[language];
  const whatsappUrl = `https://wa.me/393775952090?text=${encodeURIComponent(message)}`;
  document.querySelectorAll('a[href^="https://wa.me/"]').forEach((link) => {
    link.href = whatsappUrl;
  });
  const homeTitle = {
    it: "Autoservice Kerschbaumer — Auto, service, fiducia",
    en: "Autoservice Kerschbaumer — Cars, service, trust",
    de: "Autoservice Kerschbaumer — Autos, Service, Vertrauen"
  }[language];
  const page = document.body.dataset.page;
  document.title = page === "legal" ? copy.legalPageTitle : page === "history" ? copy.historyPageTitle : homeTitle;
  document.querySelector('meta[name="description"]').content = page === "legal"
    ? copy.legalDescription
    : page === "history" ? copy.historyDescription : copy.description;
  languageMenu.hidden = true;
  languageButton.setAttribute("aria-expanded", "false");
}

languageButton.addEventListener("click", () => {
  const isOpen = languageButton.getAttribute("aria-expanded") === "true";
  languageButton.setAttribute("aria-expanded", String(!isOpen));
  languageMenu.hidden = isOpen;
});

languageOptions.forEach((option) => {
  option.addEventListener("click", () => setLanguage(option.dataset.language));
});

document.addEventListener("click", (event) => {
  if (!event.target.closest(".language-switcher")) {
    languageMenu.hidden = true;
    languageButton.setAttribute("aria-expanded", "false");
  }
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    languageMenu.hidden = true;
    languageButton.setAttribute("aria-expanded", "false");
  }
});

menuToggle.addEventListener("click", () => {
  const isOpen = menuToggle.getAttribute("aria-expanded") === "true";
  menuToggle.setAttribute("aria-expanded", String(!isOpen));
  mainNav.classList.toggle("is-open", !isOpen);
});

mainNav.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    mainNav.classList.remove("is-open");
    menuToggle.setAttribute("aria-expanded", "false");
  });
});
